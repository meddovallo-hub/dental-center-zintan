INSERT INTO schedules(doctor_id,weekday,start_time,end_time)
SELECT dr.id,w.weekday,'08:30','15:00' FROM wanted w
JOIN doctors dr ON lower(trim(dr.name))=lower(trim(w.name))
WHERE NOT EXISTS (
 SELECT 1 FROM schedules s WHERE s.doctor_id=dr.id AND s.weekday=w.weekday
);

-- قسم الأشعة: طه الأحد/الأربعاء، الصادق الاثنين/الثلاثاء، مروان الخميس
INSERT INTO schedules(doctor_id,weekday,start_time,end_time)
SELECT dr.id,x.weekday,'08:30','15:00'
FROM (VALUES
('طه الكيلاني',0),('الصادق امبارك',1),('الصادق امبارك',2),('طه الكيلاني',3),('مروان عبد الرحمن',4)
) AS x(name,weekday)
JOIN doctors dr ON dr.name=x.name
WHERE NOT EXISTS (SELECT 1 FROM schedules s WHERE s.doctor_id=dr.id AND s.weekday=x.weekday);
